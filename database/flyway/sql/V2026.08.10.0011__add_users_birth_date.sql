-- ============================================================
-- 迁移：users 表新增 birth_date 列（未成年人保护）
-- ============================================================
-- 背景（3-N 未成年人校验）：
--   注册请求新增必填 birthDate（LocalDate），服务端校验年龄 >= 18，
--   未满 18 周岁拒绝注册并返回明确业务错误码 MINOR_NOT_ALLOWED。
--
-- 注意：
--   * birth_date 允许 NULL：存量用户无出生日期，资料更新时由前端引导补填
--     （后端 ProfileUpdate 中 birthDate 为可选字段，不破坏存量用户资料更新）
--   * 日期校验（年龄 >= 18）在应用层完成（AgePolicy），DB 仅做存储
-- ============================================================

ALTER TABLE users
    ADD COLUMN birth_date DATE NULL COMMENT '出生日期（未成年人保护，注册必填；存量用户可补填）';
