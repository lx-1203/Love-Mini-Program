-- ============================================================
-- 迁移：私信消息增加「发送者侧软删除」标记（3-G 删除消息）
-- ============================================================
-- 背景（2026-08-10）：
--   1. 微信语义：删除消息仅删除自己可见的那份，对方聊天记录不受影响；
--   2. 实现：private_messages 增加 deleted_for_sender 标记（默认 0），
--      仅当消息发送者本人删除时置 1；
--   3. 查询侧：会话消息列表按「deleted_for_sender = 0 OR sender_id <> 当前用户」
--      过滤——当前用户删除的消息对自己隐藏，对方（非发送者）仍可见；
--   4. 未读数统计不受影响：未读只统计「对方发给我」的消息，发送者本人
--      永远不会看到自己的未读，软删标记不影响该维度。
-- ============================================================

ALTER TABLE private_messages
    ADD COLUMN deleted_for_sender TINYINT(1) NOT NULL DEFAULT 0 COMMENT '发送者侧软删除标记：1=发送者本人已删除（仅对自己隐藏，对方不受影响）；默认 0';
