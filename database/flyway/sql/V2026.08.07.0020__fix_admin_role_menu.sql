-- ============================================================
-- 迁移：修复 ADMIN 角色菜单关联（排除系统管理目录 id=100）
-- ============================================================
-- 背景：
--   V2026.08.07.0012 种子 ADMIN 角色的 role_menus 关联条件为
--   m.parent_id != 100，未排除目录本身（id=100，其 parent_id=0），
--   导致校区管理员（ADMIN）菜单树中「系统管理」空目录可见。
--   本迁移清理已存在的错误关联：删除 role_id=ADMIN 与菜单 id=100 的关联。
--
--   同时后端 AdminMenuController.buildTree 已增加「剔除无可见子菜单目录」
--   兜底逻辑（双保险）。
--
-- 幂等性：DELETE 按条件删除，可安全重跑。
-- ============================================================

DELETE rm FROM role_menus rm
JOIN roles r ON r.id = rm.role_id
WHERE r.code = 'ADMIN'
  AND rm.menu_id = 100;

