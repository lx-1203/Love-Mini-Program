-- ============================================================
-- 迁移：QA 演示种子用户坐标重排（对齐开发者工具模拟器定位）
-- ============================================================
-- 背景（2026-09-12 注册链路真机验收发现）：
--   QA 种子用户（10001-10050）坐标seed 在北京一带（39.9x, 116.4x），
--   而微信开发者工具模拟器的 wx.getLocation 默认上报广州（23.13, 113.26）。
--   体验账号在模拟器内授权定位后被更新为广州坐标，推荐/附近按距离过滤
--   （客户端 NEARBY_MAX_DISTANCE_KM=20）时全部种子用户超距被滤掉，
--   导致寻觅推荐与附近的人只剩无坐标的新注册测试用户（近乎空态）。
--
--   模拟器每次定位授权都会把当前用户坐标覆盖为广州，修用户坐标无效，
--   因此把种子用户坐标重排到模拟器定位点周边（确定性抖动，全部 <20km）。
--   真机/生产环境坐标由用户上报，本迁移不影响线上数据语义（仅 QA 演示池）。
--
-- 幂等：UPDATE 固定值，可重放。抖动公式按 id 确定性展开，重复执行结果一致。
-- ============================================================

UPDATE users
SET latitude  = ROUND(23.129163 + (((CAST(id AS SIGNED) % 17) - 8) * 0.012), 6),
    longitude = ROUND(113.264435 + (((CAST(id AS SIGNED) % 13) - 6) * 0.012), 6),
    geo_updated_at = NOW()
WHERE id BETWEEN 10001 AND 10050
  AND role = 'USER'
  AND status = 'active';
